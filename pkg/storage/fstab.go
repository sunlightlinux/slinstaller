package storage

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// ProbeUUID reads a device's filesystem UUID with blkid. The UUID exists
// only once the filesystem is made, so this runs after Plan.Commands.
func ProbeUUID(device string) (string, error) {
	out, err := exec.Command("blkid", "-s", "UUID", "-o", "value", device).Output()
	if err != nil {
		return "", fmt.Errorf("storage: blkid %s: %w", device, err)
	}
	return strings.TrimSpace(string(out)), nil
}

// ProbeUUIDs reads the UUID of every partition in the plan, keyed by
// device path, for Fstab to reference.
func ProbeUUIDs(pl *Plan) (map[string]string, error) {
	uuids := make(map[string]string, len(pl.Parts))
	for _, p := range pl.Parts {
		id, err := ProbeUUID(p.Device)
		if err != nil {
			return nil, err
		}
		uuids[p.Device] = id
	}
	return uuids, nil
}

// Fstab renders /etc/fstab for the plan, given each device's UUID.
//
// Every mount is listed, swap included. This is where slinstaller parts
// from clr-installer: clr writes only non-standard mounts and lets
// systemd's gpt-auto-generator mount the rest from their GPT type codes.
// Sunlight Linux boots slinit, not systemd, so there is no generator to
// defer to — the fstab must be complete.
//
// A partition is referenced by UUID when one is known, falling back to
// its device path. The fsck pass is 1 for root, 2 for other mounts, 0
// for swap.
func (pl *Plan) Fstab(uuid map[string]string) string {
	var b strings.Builder
	b.WriteString("# /etc/fstab — generated by slinstaller\n")

	for _, p := range pl.MountOrder() {
		pass := "2"
		if p.Mountpoint == "/" {
			pass = "1"
		}
		fmt.Fprintf(&b, "%s\t%s\t%s\tdefaults\t0 %s\n",
			fstabSource(p, uuid), p.Mountpoint, p.Filesystem, pass)
	}

	for _, p := range pl.Parts {
		if p.Filesystem == "swap" {
			fmt.Fprintf(&b, "%s\tnone\tswap\tdefaults\t0 0\n", fstabSource(p, uuid))
		}
	}

	return b.String()
}

// fstabSource is how a partition is named in fstab: by UUID when known,
// otherwise by device path.
func fstabSource(p Partition, uuid map[string]string) string {
	if id := uuid[p.Device]; id != "" {
		return "UUID=" + id
	}
	return p.Device
}

// WriteFstab writes fstab content to <root>/etc/fstab, creating /etc if
// needed. root is the mounted target tree.
func WriteFstab(root, content string) error {
	dir := filepath.Join(root, "etc")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("storage: mkdir %s: %w", dir, err)
	}
	if err := os.WriteFile(filepath.Join(dir, "fstab"), []byte(content), 0o644); err != nil {
		return fmt.Errorf("storage: write fstab: %w", err)
	}
	return nil
}
